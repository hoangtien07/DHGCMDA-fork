"""Round-5 comparison per report/PREREG_R5.md. Unit = seed (per-seed value = mean over 5 folds); deltas are paired by seed.
Pre-registered effect rule: |mean delta| > 2*sd(per-seed deltas) AND same sign in all 3 seeds."""
import json, os, numpy as np
B = os.path.expanduser('~/dhg_runs/faithful/'); S = [1234, 1, 2]; R = 'v3.2_ref_MDAv3.2-3'; D3 = ['v2.0', 'v3.2_cuilab_deg2', R]
MT = {'type': ['top1_precision', 'top1_recall', 'top1_f1', 'top1_f1_micro'], 'triplet': ['auc', 'aupr', 'f1']}
def val(path, m):
    if not os.path.exists(path): return None
    v = json.load(open(path))['summary'].get(m); return None if v is None else v[0]
prim = lambda d, p, s, m: val(f'{B}results_r4/{d}_{p}_none_s{s}.json', m)
r5 = lambda name, m: val(f'{B}results_r5/{name}.json', m)
def row(label, p, base, var):
    out = []
    for m in MT[p]:
        b = [base(s, m) for s in S]; v = [var(s, m) for s in S]
        ok = [i for i in range(3) if b[i] is not None and v[i] is not None]
        if not ok: out.append(f'| {label} | {m} | – | – | – | n=0 |'); continue
        bb = np.array([b[i] for i in ok]); vv = np.array([v[i] for i in ok]); dd = vv - bb
        sd = dd.std(ddof=1) if len(dd) > 1 else float('nan')
        eff = 'n<3' if len(dd) < 3 else ('EFFECT' if abs(dd.mean()) > 2 * sd and (np.all(dd > 0) or np.all(dd < 0)) else 'no clear effect')
        out.append(f'| {label} | {m} | {bb.mean():.4f}±{bb.std(ddof=1) if len(bb)>1 else 0:.4f} | {vv.mean():.4f}±{vv.std(ddof=1) if len(vv)>1 else 0:.4f} | {dd.mean():+.4f} (signs {"".join("+" if x > 0 else "-" for x in dd)}) | {eff} |')
    return out
H = '| Comparison | Metric | Reference (mean±sd, seeds) | Variant | Δ paired | Verdict (pre-reg rule) |\n|---|---|---|---|---|---|'
L = ['# Round 5 results (auto-generated by code/compare_r5.py)\n']
L += ['## B2: ref 4-view vs ref 2-view (primary)', H]
for p in MT: L += row(f'ref 4view {p}', p, lambda s, m, p=p: prim(R, p, s, m), lambda s, m, p=p: r5(f'B2_{R}_4view_{p}_s{s}', m))
L += ['\n## B7: TDRC (same splits/metrics) vs DHGCMDA primary — Variant = TDRC; Δ = TDRC − DHGCMDA', H]
for d in D3:
    for p in MT: L += row(f'{d} {p}', p, lambda s, m, d=d, p=p: prim(d, p, s, m), lambda s, m, d=d, p=p: r5(f'B7_tdrc_{d}_{p}_s{s}', m))
for tag, suf, title in [('B3', 'rmean', 'recon_reduction=mean'), ('B4', 'full', 'predictor=full')]:
    L += [f'\n## {tag}: {title} vs primary (sensitivity, not primary)', H]
    for d in D3:
        for p in MT: L += row(f'{d} {p}', p, lambda s, m, d=d, p=p: prim(d, p, s, m), lambda s, m, d=d, p=p, tag=tag, suf=suf: r5(f'{tag}_{d}_{p}_{suf}_s{s}', m))
L += ['\n## B9a: ablations vs full model (paper claim: every removal decreases performance)', H]
for ab in ['no_cl', 'no_hgcn', 'no_avf', 'no_hgt', 'no_dv']:
    for d in ['v2.0', R]:
        for p in MT: L += row(f'{ab} {d} {p}', p, lambda s, m, d=d, p=p: prim(d, p, s, m), lambda s, m, d=d, p=p, ab=ab: r5(f'B9a_{d}_{p}_{ab}_s{s}', m))
def grid(title, items):
    out = [f'\n## {title}', '| Setting | n seeds | Top-1 P | Top-1 R | Top-1 F1 |', '|---|---|---|---|---|']; best = None
    for lab, f in items:
        vals = {m: [x for x in (f(s, m) for s in S) if x is not None] for m in ['top1_precision', 'top1_recall', 'top1_f1']}
        n = len(vals['top1_f1'])
        if n: 
            out.append(f'| {lab} | {n} | ' + ' | '.join(f'{np.mean(vals[m]):.4f}±{(np.std(vals[m], ddof=1) if n > 1 else 0):.4f}' for m in vals) + ' |')
            if best is None or np.mean(vals['top1_f1']) > best[1]: best = (lab, np.mean(vals['top1_f1']))
    out.append(f'\nargmax mean Top-1 F1: {best[0] if best else "–"}'); return out
L += grid('B9b: K sweep, v2.0 CV_type (paper: peak at K=13)', [(f'K={K}', (lambda s, m, K=K: prim('v2.0', 'type', s, m) if K == 13 else r5(f'B9b_v2.0_type_K{K}_s{s}', m))) for K in [1, 3, 5, 7, 9, 11, 13, 15]])
L += grid('B9c: (t, λ2) grid, v2.0 CV_type (paper: optimum t=0.5, λ2=0.3)', [(f't={t}, λ2={l}', (lambda s, m, t=t, l=l: prim('v2.0', 'type', s, m) if (t, l) == (0.5, 0.3) else r5(f'B9c_v2.0_type_t{t}_l{l}_s{s}', m))) for t in [0.5, 1.0, 3.0] for l in [0.1, 0.3, 0.5]])
L += ['\n## B8: test-optimised F1 vs validation-threshold F1 (all Round-5 DHGCMDA triplet jobs)', '| Job | f1 (test-opt) | f1_valthr | gap |', '|---|---|---|---|']
gaps = []
for fn in sorted(os.listdir(B + 'results_r5')):
    if 'triplet' in fn and 'tdrc' not in fn:
        a, b = r5(fn[:-5], 'f1'), r5(fn[:-5], 'f1_valthr')
        if a is not None and b is not None: gaps.append(a - b); L.append(f'| {fn[:-5]} | {a:.4f} | {b:.4f} | {a - b:+.4f} |')
if gaps: L.append(f'\nMean gap over {len(gaps)} jobs: {np.mean(gaps):+.4f} (min {min(gaps):+.4f}, max {max(gaps):+.4f})')
open(B + 'report/results_r5.md', 'w').write('\n'.join(L) + '\n'); print('\n'.join(L))
